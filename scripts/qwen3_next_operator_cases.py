"""Regenerate ``rl_engine/testing/qwen3_next_operator_cases.json`` from pytest collection.

    python scripts/qwen3_next_operator_cases.py          # check, exit 1 if stale
    python scripts/qwen3_next_operator_cases.py --write

The registry pins the exact test IDs the preflight operator gate must run. The
``norm`` and ``core`` suites are mandatory and must pass without skips;
``diagnostics`` holds the approximate cross-provider comparisons, which are
recorded but never gate. Which file and test belongs to which suite is declared
below; the IDs themselves come from collection, so a parametrisation change is
a reviewed registry diff, not a silent change in what the gate runs.
"""

import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REGISTRY = ROOT / "rl_engine/testing/qwen3_next_operator_cases.json"
NORM_FILES = ("tests/test_qwen3_next_norm.py", "tests/check_qwen3_next_norm_providers.py")
CORE_FILES = (
    "tests/check_qwen3_next_attention.py",
    "tests/check_qwen3_next_batch_invariance.py",
    "tests/check_qwen3_next_conv_bridge.py",
    "tests/check_qwen3_next_core_matrix.py",
    "tests/check_qwen3_next_forward.py",
    "tests/check_qwen3_next_gdn_bridge.py",
    "tests/check_qwen3_next_gdn_sequence.py",
    "tests/check_qwen3_next_paged_attention.py",
    "tests/check_qwen3_next_shared_core.py",
)
DIAGNOSTIC_FILES = ("tests/check_gdn_recurrent_golden.py",)
# Approximate comparisons against alternative providers, collected from the
# mandatory files above but recorded as diagnostics.
DIAGNOSTIC_TESTS = {
    "tests/check_qwen3_next_norm_providers.py": (
        "test_ours_tracks_each_vllm_path_within_bounds",
        "test_vllm_paths_disagree_only_within_bounds",
    ),
    "tests/check_qwen3_next_batch_invariance.py": (
        "test_flashinfer_chunked_prefill_deviation_stays_rounding_scale",
        "test_triton_chunked_prefill_split_matches_one_pass",
    ),
}
DESCRIPTION = (
    "Mandatory norm/core contracts; alternative-provider approximate comparisons are "
    "diagnostics only. Generated by scripts/qwen3_next_operator_cases.py; case changes "
    "require review before a frozen run."
)


def collect(files):
    out = subprocess.run(
        [sys.executable, "-m", "pytest", "--collect-only", "-q", "-p", "no:cacheprovider", *files],
        cwd=ROOT,
        capture_output=True,
        text=True,
    )
    ids = [line for line in out.stdout.splitlines() if "::test_" in line]
    if out.returncode or not ids:
        raise SystemExit(f"collection failed:\n{out.stdout[-2000:]}\n{out.stderr[-2000:]}")
    return ids


def _diagnostic(case):
    path, name = case.split("::", 1)
    return name.split("[", 1)[0] in DIAGNOSTIC_TESTS.get(path, ())


def registry():
    norm, core = collect(NORM_FILES), collect(CORE_FILES)
    diagnostics = collect(DIAGNOSTIC_FILES) + [c for c in norm + core if _diagnostic(c)]
    return {
        "schema_version": 1,
        "description": DESCRIPTION,
        "suites": {
            "norm": sorted(c for c in norm if not _diagnostic(c)),
            "core": sorted(c for c in core if not _diagnostic(c)),
            "diagnostics": sorted(diagnostics),
        },
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    text = json.dumps(registry(), indent=2) + "\n"
    if args.write:
        REGISTRY.write_text(text)
        print(f"wrote {REGISTRY.relative_to(ROOT)}")
    elif not REGISTRY.is_file() or REGISTRY.read_text() != text:
        raise SystemExit(f"{REGISTRY.relative_to(ROOT)} is stale; rerun with --write")


if __name__ == "__main__":
    main()
