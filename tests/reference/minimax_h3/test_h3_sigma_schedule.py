"""Focused tests for the MiniMax-H3 sigma grid reference (RFC #420).

Covers only the four-step construction pinned by
``MiniMaxH3Scheduler.set_timesteps`` (diffusers ``scheduling_minimax_h3.py``,
lines 148-168): ``linspace(1, 0, N)`` in fp32 -> exponential shift ->
``unique_consecutive`` -> ``timesteps = 1 - sigmas[:-1]``.

The primary oracle is ``h3_sigma_schedule_upstream_fixture.json``: fp32 bit
patterns produced by actually executing the upstream method (AST-extracted
and run as-is, see ``make_upstream_fixture.py``) from the source file with
git blob sha ``ca69ae6a2f6aae5bb68498216316a71eb07c1f7b`` (diffusers commit
``f53d552``, the only revision that touched the file). That check needs
no network, no installed diffusers, and never skips.
"""

from __future__ import annotations

import json
import pathlib

import pytest
import torch

from rl_engine.reference.minimax_h3.sigma_schedule import NativeH3SigmaScheduleOp

_OP = NativeH3SigmaScheduleOp()

# RFC #420 fingerprint shifts: video 12.0, audio 3.0 (H12 — one grid per
# modality; grids must never be shared implicitly).
_CASES = [
    (2, 12.0),
    (2, 3.0),
    (8, 12.0),
    (8, 3.0),
    (25, 12.0),
    (25, 3.0),
    (50, 12.0),
    (50, 3.0),
    (1000, 12.0),
    (1000, 3.0),
]


_FIXTURE_PATH = pathlib.Path(__file__).parent / "h3_sigma_schedule_upstream_fixture.json"
_UPSTREAM_BLOB_SHA = "ca69ae6a2f6aae5bb68498216316a71eb07c1f7b"
_EXPECTED_CASES = {(2, 3.0), (2, 12.0), (4, 3.0), (4, 12.0), (25, 3.0), (25, 12.0)}


def _int32_bits(tensor: torch.Tensor) -> list[int]:
    return tensor.detach().contiguous().view(torch.int32).tolist()


def _bits_to_int32(bits: list[str]) -> torch.Tensor:
    return torch.tensor([int(value, 16) for value in bits], dtype=torch.int32)


def test_matches_pinned_upstream_set_timesteps_bitwise():
    # Non-skippable: the expected fp32 bit patterns were generated by actually
    # executing the upstream set_timesteps method from the pinned source (see
    # make_upstream_fixture.py) — no network, no diffusers install, and no
    # hand-copied formula are involved.
    fixture = json.loads(_FIXTURE_PATH.read_text(encoding="utf-8"))
    assert fixture["upstream"]["blob_sha1"] == _UPSTREAM_BLOB_SHA

    actual_cases = [(case["num_inference_steps"], case["shift"]) for case in fixture["cases"]]
    assert len(actual_cases) == len(set(actual_cases)), "duplicate fixture cases"
    assert set(actual_cases) == _EXPECTED_CASES

    for case in fixture["cases"]:
        schedule = _OP(case["num_inference_steps"], shift=case["shift"])

        assert schedule.sigmas.dtype is torch.float32
        assert tuple(schedule.sigmas.shape) == (case["sigmas_count"],)
        assert _int32_bits(schedule.sigmas) == _bits_to_int32(case["sigmas_bits"]).tolist()

        assert schedule.timesteps.dtype is torch.float32
        assert tuple(schedule.timesteps.shape) == (case["timesteps_count"],)
        expected_timesteps = _bits_to_int32(case["timesteps_bits"]).tolist()
        assert _int32_bits(schedule.timesteps) == expected_timesteps

        assert schedule.num_model_evals == case["num_model_evals"]


@pytest.mark.parametrize(("num_inference_steps", "shift"), _CASES)
def test_grid_invariants(num_inference_steps, shift):
    schedule = _OP(num_inference_steps, shift=shift)
    sigmas, timesteps = schedule.sigmas, schedule.timesteps

    assert sigmas.dtype is torch.float32
    assert timesteps.dtype is torch.float32
    assert sigmas.numel() <= num_inference_steps
    # First sigma is exactly 1.0 for the released shifts (3.0, 12.0); the
    # shift maps the terminal 0.0 to exactly 0.0.
    assert sigmas[0].item() == 1.0
    assert sigmas[-1].item() == 0.0
    assert bool((sigmas[1:] < sigmas[:-1]).all())
    assert bool((timesteps[1:] > timesteps[:-1]).all())
    assert timesteps[0].item() == 0.0
    # Call count follows the deduplicated grid, not the requested N.
    assert schedule.num_model_evals == sigmas.numel() - 1 == timesteps.numel()


def test_unique_consecutive_collapses_shift_created_collisions():
    # shift=12 compresses spacing near sigma=1 enough that a dense grid holds
    # fp32 collisions: N=1e6 collapses ~4% of rows in a few ms. The base
    # linspace itself stays duplicate-free at this density, so the collapse is
    # attributable to the shift step, as the upstream docstring claims.
    n = 1_000_000
    base = torch.linspace(1.0, 0.0, n, dtype=torch.float32)
    assert torch.unique_consecutive(base).numel() == n  # precondition

    schedule = _OP(n, shift=12.0)

    assert schedule.sigmas.numel() < n
    assert schedule.num_model_evals == schedule.sigmas.numel() - 1
    assert schedule.timesteps.numel() == schedule.num_model_evals
    assert bool((schedule.sigmas[1:] < schedule.sigmas[:-1]).all())
    assert schedule.sigmas[-1].item() == 0.0


def test_video_and_audio_shifts_give_distinct_grids():
    video = _OP(25, shift=12.0)
    audio = _OP(25, shift=3.0)

    assert not torch.equal(video.sigmas, audio.sigmas)
    assert not torch.equal(video.timesteps, audio.timesteps)


@pytest.mark.parametrize("num_inference_steps", [1, 0, -4])
def test_rejects_num_inference_steps_below_two(num_inference_steps):
    with pytest.raises(ValueError, match="num_inference_steps"):
        _OP(num_inference_steps, shift=12.0)


@pytest.mark.parametrize("shift", [0.0, -1.5])
def test_rejects_non_positive_shift(shift):
    with pytest.raises(ValueError, match="positive"):
        _OP(8, shift=shift)


def test_device_argument_preserves_bytes_and_dtype():
    local = _OP(25, shift=12.0)
    moved = _OP(25, shift=12.0, device="cpu")

    assert _int32_bits(moved.sigmas) == _int32_bits(local.sigmas)
    assert _int32_bits(moved.timesteps) == _int32_bits(local.timesteps)
    assert moved.sigmas.dtype is torch.float32
    assert moved.sigmas.device.type == "cpu"


def test_builds_on_cpu_under_non_cpu_default_device():
    # torch.linspace without an explicit device follows the ambient default
    # device, so the reference must pin "cpu" itself. Under a meta default the
    # unfixed implementation raised NotImplementedError inside
    # unique_consecutive (no meta kernel); on real accelerators it would
    # silently build the grid off-CPU.
    with torch.device("meta"):
        schedule = _OP(25, shift=12.0)

    assert schedule.sigmas.device.type == "cpu"
    assert schedule.timesteps.device.type == "cpu"
    reference = _OP(25, shift=12.0)
    assert _int32_bits(schedule.sigmas) == _int32_bits(reference.sigmas)
    assert _int32_bits(schedule.timesteps) == _int32_bits(reference.timesteps)


def test_matches_installed_diffusers_scheduler_when_available():
    diffusers = pytest.importorskip("diffusers")
    scheduler_cls = getattr(diffusers, "MiniMaxH3Scheduler", None)
    if scheduler_cls is None:
        pytest.skip("installed diffusers has no MiniMaxH3Scheduler")

    for num_inference_steps, shift in ((25, 12.0), (50, 3.0)):
        scheduler = scheduler_cls(shift=shift)
        scheduler.set_timesteps(num_inference_steps, device="cpu")
        schedule = _OP(num_inference_steps, shift=shift)

        assert torch.equal(scheduler.sigmas, schedule.sigmas)
        assert torch.equal(scheduler.timesteps, schedule.timesteps)
        # Upstream stores len(timesteps) as num_inference_steps, i.e. the
        # model-evaluation count.
        assert scheduler.num_inference_steps == schedule.num_model_evals
